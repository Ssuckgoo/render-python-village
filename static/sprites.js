const spriteCache = {};
function buildSprite(name, opt = {}) {
  const key = name + '|' + (opt.cloth || '') + (opt.flash ? 'f' : '');
  if (spriteCache[key]) return spriteCache[key];
  const rows = SPRITES[name] || SPRITES.rock;
  const c = document.createElement('canvas');
  c.width = 16; c.height = 16;
  const ctx = c.getContext('2d');
  rows.forEach((row, y) => {
    for (let x = 0; x < 16; x++) {
      const ch = row[x];
      if (!ch || ch === '.') continue;
      ctx.fillStyle = opt.flash ? '#ffffff' : ch === 'C' ? (opt.cloth || '#5b8cff') : (PAL[ch] || '#ff00ff');
      ctx.fillRect(x, y, 1, 1);
    }
  });
  spriteCache[key] = c;
  return c;
}
